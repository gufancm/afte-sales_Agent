"""工作流依赖容器（依赖注入）。节点通过它访问 LLM/Policy/RAG/外部端口/仓储。

权限分层：图节点只拿到只读端口（`ReadOnly*Port`）；可写端口只存在于 `tools`（WriteTools），
仅供 SagaDispatcher / Worker / 联调脚本使用，图节点不得引用 `deps.tools`。
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol

from app.config import Settings
from app.llm.adapter import OpenAICompatibleLLM
from app.mcp.gateway import WriteTools
from app.mcp.ports import ReadOnlyFinancePort, ReadOnlyLogisticsPort, ReadOnlyOrderPort
from app.policy.engine import PolicyEngine
from app.rag.retrieval import Retriever


class PersistencePort(Protocol):
    """业务持久化端口：工单/消息/运行/计划/审批/退款/命令/审计/llm_calls/tool_calls。"""

    async def record_llm_call(self, **kw: Any) -> None: ...
    async def record_tool_call(self, **kw: Any) -> None: ...
    async def upsert_intent(self, *, tenant_id: str, ticket_id: str, intent: str,
                            expected_version: int | None = None) -> bool: ...
    async def record_policy_decision(self, **kw: Any) -> str: ...
    async def list_command_statuses(self, *, tenant_id: str, command_ids: list[str]) -> list[dict]: ...
    async def create_refund_request(self, **kw: Any) -> str: ...
    async def insert_quote(self, **kw: Any) -> None: ...
    async def create_plan_draft(self, **kw: Any) -> str: ...
    async def freeze_plan(self, **kw: Any) -> None: ...
    async def ensure_approval_task(self, **kw: Any) -> dict: ...
    async def load_and_verify_approval(self, **kw: Any) -> dict: ...
    async def decide_approval(self, *, tenant_id: str, approval_id: str, decision: str, reviewer_id: str,
                              reviewer_role: str | None = None, comment: str | None = None,
                              allowed_roles: list[str] | None = None) -> None: ...
    async def enqueue_command(self, **kw: Any) -> str: ...
    async def create_reconciliation_task(self, **kw: Any) -> str: ...
    async def ensure_policy_review_task(self, **kw: Any) -> str: ...
    async def append_audit(self, **kw: Any) -> None: ...
    async def record_risk_decision(self, **kw: Any) -> str: ...
    # ---- 记忆系统（短期跨轮 / 情景 / 语义）----
    async def get_ticket(self, *, tenant_id: str, ticket_id: str) -> dict | None: ...
    async def append_message(self, **kw: Any) -> str: ...
    async def list_messages(self, *, tenant_id: str, ticket_id: str, limit: int = 40) -> list[dict]: ...
    async def get_conversation_summary(self, *, tenant_id: str, ticket_id: str) -> dict | None: ...
    async def upsert_conversation_summary(self, *, tenant_id: str, ticket_id: str, summary: str,
                                          up_to_message_count: int) -> None: ...
    async def insert_episodic_memory(self, **kw: Any) -> str: ...
    async def search_episodic_memories(self, *, tenant_id: str, user_id: str,
                                       query_embedding: list, top_k: int) -> list[dict]: ...
    async def get_user_profile(self, *, tenant_id: str, user_id: str) -> dict | None: ...
    async def upsert_user_profile(self, *, tenant_id: str, user_id: str, profile: dict) -> None: ...


@dataclass
class Deps:
    settings: Settings
    llm: OpenAICompatibleLLM | None
    policy: PolicyEngine
    retriever: Retriever
    orders: ReadOnlyOrderPort
    logistics: ReadOnlyLogisticsPort
    finance: ReadOnlyFinancePort
    persistence: PersistencePort
    prompts: dict[str, str]
    # 二级模型路由用的小模型客户端；为 None 表示未启用分级（一律走主模型）
    llm_small: OpenAICompatibleLLM | None = None
    # 原始（可写）端口集合：仅 SagaDispatcher/Worker/联调脚本持有；图节点不得引用
    tools: WriteTools | None = None
    # 记忆服务（短期跨轮 / 情景 / 语义）；非权威，仅用于理解与措辞，且失败即降级
    memory: Any = None
    # 运行期由 main 装配；测试可直接赋值
    graph: Any = None
    v4_graph: Any = None
